-- 0044: регламент можно править из интерфейса.
--
--   До этого duty_templates заводились только сидом: в приложении не было ни
--   права, ни экрана, ни ручки API. Правило владельца: директор меняет
--   регламент кому угодно, включая себя; старший менеджер — кому угодно, кроме
--   СВОЕГО (иначе он сам себе снимает обязанности и сдвигает дедлайны).
--
--   Само правило «не свой регламент» живёт в API (src/shared/duties.ts):
--   в политике RLS его не выразить — profiles.id и auth.uid() у нас разные
--   сущности, а все записи и так идут сервисным ключом с проверкой can().
--   Здесь только выравниваем политику под новую роль и добавляем след правки:
--   кто и когда трогал регламент — вопрос дисциплины, а не догадок.
-- ─────────────────────────────────────────────────────────────────────────────

alter table duty_templates
  add column updated_at timestamptz,
  add column updated_by uuid references profiles(id) on delete set null;

drop policy if exists duty_templates_write on duty_templates;
create policy duty_templates_write on duty_templates
  for all using (auth_role(org_id) in ('owner', 'admin', 'manager'));
