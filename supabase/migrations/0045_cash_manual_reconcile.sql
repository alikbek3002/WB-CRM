-- ─────────────────────────────────────────────────────────────────────────────
-- 0045: Касса ведётся человеком. Автоматические «поступления от WB» убраны.
--
--   ЧТО БЫЛО НЕ ТАК. Синк заводил приход в кассу по шапкам отчётов реализации
--   (rpc agg_wb_payouts → «итого к оплате» за отчётный период). Это НЕ то, что
--   упало на расчётный счёт: маркетплейс держит деньги до вывода, удерживает по
--   другим периодам, платит частями и в другие даты. В базе так набралось 12
--   операций на 198,8 млн сом, которых на счетах нет — «всего денег» врало,
--   и поправить это директор не мог: касса складывалась из этих операций.
--
--   РЕШЕНИЕ. Деньги в кассе вводит человек — как в жизни, по банковской выписке:
--     • синк больше не создаёт выплаты WB (src/backend/wb/sync.ts);
--     • уже созданные удаляем (ниже);
--     • появляется СВЕРКА: директор вписывает фактический остаток счёта, а
--       разницу система пишет корректирующей операцией (source='adjustment')
--       со статьёй «Сверка кассы» — остаток становится верным, и видно, кто и
--       когда его правил;
--     • ошибочную операцию можно удалить прямо из ленты кассы.
--   Баланс кабинета WB (wb_balance) остаётся справочной строкой «маркетплейс
--   ещё не перечислил» — в «всего денег» он и не входил.
-- ─────────────────────────────────────────────────────────────────────────────

-- Новый источник операции: корректировка остатка по сверке
alter table cash_tx drop constraint if exists cash_tx_source_check;
alter table cash_tx add constraint cash_tx_source_check
  check (source in ('manual','bot','ai','supply_payment','wb_payout','payout','adjustment'));

comment on column cash_tx.source is
  'Откуда операция: рука, бот, ИИ, оплата поставки, выплата WB, заявка, сверка остатка';

------------------------------------------------------------------------------
-- Статьи сверки. in_pnl = false: корректировка остатка — не доход и не расход
-- периода, иначе прибыль поедет от технической правки кассы.
------------------------------------------------------------------------------

insert into expense_categories (org_id, name, direction, in_pnl, emoji, sort_order)
select o.id, c.name, c.direction, false, '🧮', 900
from orgs o
cross join (values
  ('Сверка кассы: излишек', 'in'),
  ('Сверка кассы: недостача', 'out')
) as c(name, direction)
on conflict (org_id, name) do nothing;

------------------------------------------------------------------------------
-- Чистим кассу от автоматических выплат WB (решение директора: суммы неверные).
-- Отчёты реализации при этом никуда не деваются — ОПиУ и «Выплаты WB» считаются
-- из raw_finance_report, а не из этих операций.
------------------------------------------------------------------------------

delete from cash_tx where source = 'wb_payout';

------------------------------------------------------------------------------
-- Ловушка в сидовых счетах: «Наличные», «Расчётный счёт» и «Карта» заведены
-- миграцией 0024 в РУБЛЯХ (тогда базовой валютой считался рубль). Компания
-- живёт в сомах: директор впишет в сверку сомовый остаток, а система умножит
-- его на курс рубля и завысит деньги на 10%. Переводим в сом пустые рублёвые
-- счета — на них ещё нет ни одной операции, терять нечего. Счета С операциями
-- не трогаем: валюта уже вписана в каждую проводку.
------------------------------------------------------------------------------

update cash_accounts a set currency = 'kgs'
where a.currency = 'rub'
  and not exists (
    select 1 from cash_tx t
    where t.account_id = a.id or t.to_account_id = a.id
  );
