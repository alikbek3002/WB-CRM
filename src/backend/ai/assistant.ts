// Сколько шагов «модель → инструмент → модель» разрешаем за один запрос.
// Реальные цепочки: найти сотрудника → поставить задачу; завести фабрику →
// создать поставку → записать оплату. 4 шагов не хватало — обрывалось на
// середине сценария; 10 покрывает всё, что делают руками за один заход.
const MAX_AGENT_STEPS = 10;

// Вызов Claude с историей и инструментами (агент-цикл).
// db нужен для исполнения инструментов; без него ассистент работает только «на чтение».
// onMutation вызывается, если инструмент ЗАПИСАЛ что-то в БД — вызывающая сторона
// сбрасывает кэш чтения (в Next — revalidateTag, в боте — HTTP-пинг в веб).
export async function askAssistant(params: {
  user: SnapshotUser;
  snapshot: string;
  history: ChatMessage[];
  db?: SupabaseClient;
  channel?: Channel; // как оформлять ответ (по умолчанию — веб)
  onMutation?: () => void;
}): Promise<string> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    return "ИИ-ассистент пока не подключён. Добавьте ANTHROPIC_API_KEY в настройки.";
  }
  const { default: Anthropic } = await import("@anthropic-ai/sdk");
  const client = new Anthropic({ apiKey });

  // Последние 12 сообщений истории — держим контекст, но не раздуваем
  const history = params.history.slice(-12).filter((m) => m.content.trim());
  if (!history.length || history[history.length - 1].role !== "user") {
    return "Задайте вопрос — например: «Какой товар продаётся лучше всего?» или «Выполняем ли план?»";
  }

  // Описания инструментов — это заметный объём токенов на КАЖДОМ шаге цикла.
  // Метка на последнем инструменте кэширует весь блок tools; метка на system
  // кэширует tools+system. Префикс одинаков внутри роли → со второго шага
  // диалога оба блока читаются из кэша.
  const tools = params.db ? toolsForRole(params.user.role) : [];
  const cachedTools = tools.length
    ? tools.map((t, i) =>
        i === tools.length - 1 ? { ...t, cache_control: { type: "ephemeral" as const } } : t,
      )
    : undefined;
  const system = [
    {
      type: "text" as const,
      text: systemPrompt(params.user, params.snapshot, params.channel ?? "web"),
      cache_control: { type: "ephemeral" as const },
    },
  ];

  // Агент-цикл: модель может позвать инструмент → исполняем → возвращаем результат
  type AnyMessage = { role: "user" | "assistant"; content: unknown };
  const messages: AnyMessage[] = history.map((m) => ({ role: m.role, content: m.content }));

  for (let step = 0; step < MAX_AGENT_STEPS; step++) {
    const res = await client.messages.create({
      model: AI_MODEL,
      max_tokens: 2048,
      system,
      tools: cachedTools as never,
      // История собрана из наших же структур — форма совместима с API
      messages: messages as never,
    });

    if (res.stop_reason === "tool_use" && params.db) {
      // Инструменты одного шага независимы — исполняем параллельно, чтобы
      // цепочка из нескольких действий не превращалась в сумму задержек БД.
      const calls = res.content.filter((b) => b.type === "tool_use");
      const toolResults = await Promise.all(
        calls.map(async (block) => ({
          type: "tool_result",
          tool_use_id: block.id,
          content: await executeTool(
            params.db!,
            params.user,
            block.name,
            (block.input ?? {}) as Record<string, unknown>,
            params.onMutation,
          ),
        })),
      );
      messages.push({ role: "assistant", content: res.content });
      messages.push({ role: "user", content: toolResults });
      continue;
    }

    const text = res.content.find((b) => b.type === "text");
    return text && text.type === "text"
      ? text.text.trim()
      : "Не удалось сформировать ответ, попробуйте переформулировать.";
  }
  return "Действие оказалось сложнее, чем ожидалось — попробуйте разбить запрос на шаги.";
}
